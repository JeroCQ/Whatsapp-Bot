"""Render a data-free, namespaced copy of an inspected bot schema.

Reads a catalog manifest from central_schema_manifest.sql. Never reads credentials,
changes a live source, executes SQL or changes source message/customer IDs.
"""
import argparse
import hashlib
import json
import re


def ident(value):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError("Unsupported database identifier")
    return '"' + value + '"'


def literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def render(manifest, business):
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,39}", business):
        raise ValueError("Invalid business")
    prefix = "chatty_" + business + "_"
    tables = manifest["tables"]
    required = {"customers", "conversation_states", "message_logs", "processed_webhook_events",
                "dashboard_admins", "catalog_assets", "handoff_deliveries", "crm_control_commands",
                "crm_send_attempts", "crm_media_assets"}
    if {item["name"] for item in tables} != required:
        raise ValueError("The complete bot/control/media schema is required")
    names = {item["name"] for group in (tables, manifest["enums"], manifest["sequences"]) for item in group}
    for table in tables:
        names.update(item["name"] for item in table["constraints"])
        for index in table["indexes"]:
            match = re.match(r'CREATE (?:UNIQUE )?INDEX (?:"([^"]+)"|([a-zA-Z0-9_]+)) ', index)
            if not match:
                raise ValueError("Unsupported index definition")
            names.add(match[1] or match[2])
    for function in manifest["functions"]:
        match = re.match(r"CREATE OR REPLACE FUNCTION public\.([a-zA-Z0-9_]+)\(", function)
        if not match or match[1] not in {"crm_control_dispatch", "crm_control_view"}:
            raise ValueError("Unexpected privileged function")
        names.add(match[1])
    def target_name(name):
        value = prefix + name
        if len(value) > 63:
            value = value[:54] + "_" + hashlib.sha256(value.encode()).hexdigest()[:8]
        return value
    if any(len(prefix + table["name"]) > 63 for table in tables):
        raise ValueError("Business identifier is too long for the legacy table contract")
    targets = {name: target_name(name) for name in names}
    pattern = re.compile(r"\b(" + "|".join(re.escape(name) for name in sorted(names, key=len, reverse=True)) + r")\b")
    def rename(value):
        return pattern.sub(lambda match: targets[match[0]], value)
    sql = ["-- Central storage for " + business + "; original source stays untouched.",
           "DO $$ BEGIN IF to_regclass(" + literal("public." + prefix + "customers")
           + ") IS NOT NULL THEN RAISE EXCEPTION 'central_namespace_already_exists'; END IF; END $$;"]
    for enum in manifest["enums"]:
        sql.append("CREATE TYPE public." + ident(prefix + enum["name"]) + " AS ENUM ("
                   + ",".join(literal(item) for item in enum["values"]) + ");")
    for sequence in manifest["sequences"]:
        sql.append("CREATE SEQUENCE public." + ident(prefix + sequence["name"])
                   + " AS " + sequence["type"] + " INCREMENT BY " + str(sequence["increment"])
                   + " MINVALUE " + str(sequence["min"]) + " MAXVALUE " + str(sequence["max"])
                   + " START WITH " + str(sequence["start"]) + " CACHE " + str(sequence["cache"])
                   + (" CYCLE" if sequence["cycle"] else " NO CYCLE") + ";")
    for table in tables:
        columns = []
        for column in table["columns"]:
            value = ident(column["name"]) + " " + rename(column["type"])
            if column["identity"]:
                value += " GENERATED BY DEFAULT AS IDENTITY"
            elif column["default"] is not None:
                value += " DEFAULT " + rename(column["default"])
            if column["not_null"]:
                value += " NOT NULL"
            columns.append(value)
        sql.append("CREATE TABLE public." + ident(prefix + table["name"]) + " (\n  "
                   + ",\n  ".join(columns) + "\n);")
    for foreign_keys in (False, True):
        for table in tables:
            for constraint in table["constraints"]:
                if (constraint["type"] == "f") != foreign_keys:
                    continue
                sql.append("ALTER TABLE public." + ident(prefix + table["name"])
                           + " ADD CONSTRAINT " + ident(targets[constraint["name"]])
                           + " " + rename(constraint["definition"]) + ";")
    for table in tables:
        sql.extend(rename(index) + ";" for index in table["indexes"])
        target = "public." + ident(prefix + table["name"])
        sql.extend(["ALTER TABLE " + target + " ENABLE ROW LEVEL SECURITY;",
                    "REVOKE ALL ON TABLE " + target + " FROM PUBLIC, anon, authenticated;",
                    "GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE " + target + " TO service_role;"])
    for sequence in manifest["sequences"]:
        sql.append("GRANT USAGE,SELECT,UPDATE ON SEQUENCE public." + ident(prefix + sequence["name"]) + " TO service_role;")
    for function in manifest["functions"]:
        sql.append(rename(function).rstrip().rstrip(";") + ";")
    for name, signature in (("crm_control_dispatch", "text,text,text,text,text,bigint,jsonb"),
                            ("crm_control_view", "text,text")):
        function = "public." + ident(prefix + name) + "(" + signature + ")"
        sql.extend(["REVOKE ALL ON FUNCTION " + function + " FROM PUBLIC,anon,authenticated;",
                    "GRANT EXECUTE ON FUNCTION " + function + " TO service_role;"])
    sql.append("NOTIFY pgrst, 'reload schema';")
    return "\n\n".join(sql) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--business", required=True)
    args = parser.parse_args()
    with open(args.manifest, encoding="utf-8") as source:
        manifest = json.load(source)
    print(render(manifest, args.business), end="")


if __name__ == "__main__":
    main()
